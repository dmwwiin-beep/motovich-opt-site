-- Optional Web Push subscription storage for MOTOVICH.
-- Apply after 202610210001_motovich_cloud.sql.
begin;

create table if not exists public.motovich_push_subscriptions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  endpoint text not null unique,
  p256dh text not null,
  auth_secret text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint motovich_push_endpoint_https check (endpoint like 'https://%'),
  constraint motovich_push_endpoint_len check (length(endpoint) between 20 and 2048),
  constraint motovich_push_p256dh_len check (length(p256dh) between 16 and 256),
  constraint motovich_push_auth_len check (length(auth_secret) between 8 and 128)
);

alter table public.motovich_push_subscriptions enable row level security;
revoke all on table public.motovich_push_subscriptions from anon, authenticated;
grant select, insert, update, delete on table public.motovich_push_subscriptions to authenticated;

drop policy if exists "motovich push select own" on public.motovich_push_subscriptions;
drop policy if exists "motovich push insert own" on public.motovich_push_subscriptions;
drop policy if exists "motovich push update own" on public.motovich_push_subscriptions;
drop policy if exists "motovich push delete own" on public.motovich_push_subscriptions;

create policy "motovich push select own"
  on public.motovich_push_subscriptions for select to authenticated
  using ((select auth.uid()) = user_id);
create policy "motovich push insert own"
  on public.motovich_push_subscriptions for insert to authenticated
  with check ((select auth.uid()) = user_id);
create policy "motovich push update own"
  on public.motovich_push_subscriptions for update to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);
create policy "motovich push delete own"
  on public.motovich_push_subscriptions for delete to authenticated
  using ((select auth.uid()) = user_id);

create or replace function public.motovich_touch_push_subscription()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists motovich_push_subscription_touch on public.motovich_push_subscriptions;
create trigger motovich_push_subscription_touch
  before update on public.motovich_push_subscriptions
  for each row execute function public.motovich_touch_push_subscription();

commit;
