-- Due-task Push delivery ledger. Server-only table; no browser role can read it.
begin;

create table if not exists public.motovich_push_deliveries (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  task_id text not null,
  due_on text not null check (due_on ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}$'),
  status text not null default 'sending' check (status in ('sending', 'sent', 'failed')),
  claim_token text not null default gen_random_uuid()::text,
  attempts integer not null default 1 check (attempts between 1 and 100),
  last_attempt_at timestamptz not null default now(),
  sent_at timestamptz,
  error_code text,
  created_at timestamptz not null default now(),
  constraint motovich_push_delivery_once unique (user_id, task_id, due_on)
);

create index if not exists motovich_push_deliveries_user_created
  on public.motovich_push_deliveries (user_id, created_at desc);

alter table public.motovich_push_deliveries enable row level security;
revoke all on table public.motovich_push_deliveries from anon, authenticated;
grant all on table public.motovich_push_deliveries to service_role;
grant usage, select on sequence public.motovich_push_deliveries_id_seq to service_role;

commit;
